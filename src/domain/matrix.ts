import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { loadCatalogue, loadMappings, loadProfile, type ControlDefinition, type Profile } from './definitions.js';

export interface MatrixOptions {
  readonly matrixPath: string;
  readonly reviewSheetPath: string;
}

const escapeCell = (value: string): string => value.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/**
 * `automated` only when every declared method runs by the runner. One manual method makes the
 * control `mixed`, because tool evidence alone cannot satisfy it. `manual_only` when nothing is
 * automated, in which case a scan result can never satisfy the control at all.
 */
function coverage(control: ControlDefinition): 'automated' | 'mixed' | 'manual_only' {
  const coverages = control.verification.map((entry) => entry.coverage);
  if (coverages.every((value) => value === 'automated')) return 'automated';
  if (coverages.some((value) => value === 'automated')) return 'mixed';
  return 'manual_only';
}

function methods(control: ControlDefinition): string {
  return [...new Set(control.verification.map((entry) => (entry.recipe ? `${entry.method} (${entry.recipe})` : entry.method)))].join(', ');
}

function applicabilityText(control: ControlDefinition): string {
  const applicability = control.applicability;
  switch (applicability.rule) {
    case 'always':
      return 'All applications';
    case 'when_environment':
      return `Environments: ${(applicability.environments ?? []).join(', ')}`;
    case 'when_any_feature_enabled':
      return `Any of: ${(applicability.features ?? []).join(', ')}`;
    default:
      return `${applicability.rule}: ${(applicability.features ?? []).join(', ') || applicability.environments?.join(', ') || 'all'}`;
  }
}

function selectedBy(controlId: string, profiles: readonly Profile[]): string[] {
  return profiles.filter((profile) => profile.controls.some((entry) => entry.control === controlId)).map((profile) => profile.id);
}

function bullets(items: readonly string[]): string {
  return items.map((item) => `<li>${escapeCell(item)}</li>`).join('');
}

/**
 * Generates the coverage matrix and the owner review sheet from the same definitions the runner
 * uses, so a generated document cannot drift from what actually gates. Output is deterministic:
 * running it twice on unchanged inputs produces identical files.
 */
export function generateMatrix(options: MatrixOptions): { readonly matrixPath: string; readonly reviewSheetPath: string } {
  const catalogue = loadCatalogue();
  const mappings = loadMappings();
  const profiles = [loadProfile('core'), loadProfile('nextjs-supabase')];

  const matrix = [
    '# Control coverage matrix',
    '',
    'Generated by `npm run generate:matrix`. Do not edit by hand: this file is produced from the same',
    'definitions the runner uses, so it cannot drift from what actually gates.',
    '',
    `- Catalogue version: ${catalogue.catalogue_version}`,
    `- Controls: ${catalogue.controls.length}`,
    `- All definitions draft: ${catalogue.controls.every((control) => control.review_status === 'draft')}`,
    `- Standards mappings reviewed: ${mappings.reviewed}`,
    `- Generated at catalogue version ${catalogue.catalogue_version}; a different catalogue version means regenerating.`,
    '',
    '| Control | Title | Applicability | Verification | Coverage | Owner role | Review status | In profiles | Standards |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...catalogue.controls.map((control) => {
      const standards = (mappings.controls[control.id] ?? [])
        .map((mapping) => `${mapping.framework}${mapping.requirement ? ` (${escapeCell(mapping.requirement)})` : ''} [${mapping.relationship}]`)
        .join('<br>');
      const inProfiles = selectedBy(control.id, profiles).join(', ') || '—';
      return `| **${control.id}** | ${escapeCell(control.title)} | ${escapeCell(applicabilityText(control))} | ${escapeCell(methods(control))} | ${coverage(control)} | ${escapeCell(control.owner_role)} | ${control.review_status} | ${inProfiles} | ${standards || '—'} |`;
    }),
    '',
    '## Coverage classification',
    '',
    '- **automated** — every declared verification method runs by the runner.',
    '- **mixed** — tool evidence plus reviewed manual or configuration evidence. Partial work is never',
    '  silently accepted; both parts are required.',
    '- **manual_only** — no automation. A scan result can never satisfy these.',
    '',
    '## Unsupported and excluded scope',
    '',
    ...profiles.flatMap((profile) => {
      const excluded = (profile.excluded_features ?? []).map((feature) => `\`${feature}\``).join(', ') || 'none';
      return [
        `- \`${profile.id}\` excludes: ${excluded}. Enabling an excluded feature produces a coverage gap`,
        '  and an additional verification requirement. It never produces an implied pass.',
      ];
    }),
    '',
    '## Standards mappings',
    '',
    mappings.reviewed
      ? 'Mappings have been reviewed against their pinned source editions.'
      : `**No mapping has been reviewed against a pinned source edition.** ${mappings.review_note ?? ''}`,
    '',
    ...Object.entries(mappings.editions).map(([framework, edition]) => `- ${framework} ${edition.edition} (${edition.status}) — ${edition.source}`),
    '',
  ].join('\n');

  const sheet = [
    '# Control review sheet',
    '',
    'One row per control for owner review. Every definition below is `review_status: draft`; only the',
    'owner changes it to `owner_reviewed` with a reviewer name and date. Do not approve a row whose',
    'acceptance criteria describe something you have not verified exists.',
    '',
    `Catalogue version ${catalogue.catalogue_version} · ${catalogue.controls.length} controls · generated by \`npm run generate:matrix\``,
    '',
    '| # | ID | Title | Applies when | Acceptance criteria (summary) | Verification method | Stated limitations | In profiles |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...catalogue.controls.map((control, index) => {
      const inProfiles = selectedBy(control.id, profiles).join(', ') || '—';
      return `| ${index + 1} | **${control.id}** | ${escapeCell(control.title)} | ${escapeCell(applicabilityText(control))} | <ul>${bullets(control.acceptance)}</ul> | ${escapeCell(methods(control))} | <ul>${bullets(control.limitations)}</ul> | ${inProfiles} |`;
    }),
    '',
    '## What to check on each row',
    '',
    '1. Does the applicability condition match when you would actually want this control?',
    '2. Is each acceptance criterion testable, or is it a wish?',
    '3. Is the stated verification method real, or aspirational? A method with no implemented recipe',
    '   must be `manual_only` until the recipe exists.',
    '4. Are the limitations honest about what the method does not cover?',
    '5. Is a control missing entirely from your threat model?',
    '',
    '## Deviations from the blueprint',
    '',
    'Acceptance criteria were written concisely from blueprint section 6 rather than copied verbatim.',
    'No control was added, removed, or merged. Per-control wording is in `controls/controls.yaml`.',
    'The `related_risk` mappings are the only change of substance: no exact standards requirement IDs',
    'are asserted anywhere, because no mapping has been reviewed against a pinned source edition yet.',
    '',
  ].join('\n');

  for (const [file, contents] of [
    [options.matrixPath, matrix],
    [options.reviewSheetPath, sheet],
  ] as const) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, contents, 'utf8');
  }

  return { matrixPath: options.matrixPath, reviewSheetPath: options.reviewSheetPath };
}
