/**
 * `hardening audit PATH` — point it at any folder and get a complete, honest report (Batch U).
 *
 * Contract, from the remediation plan and the gap analysis:
 *
 * - **It never writes to the audited project.** All output goes to `--out`, which must live
 *   outside the target; the tree-digest test proves the audited tree is byte-identical afterwards.
 * - **It runs inside the existing machinery** — a generated (ephemeral) manifest, then the real
 *   plan, check, and gate. Audit mode does not bypass the evaluator; it just does not require the
 *   audited project to have written a manifest first.
 * - **It never executes application code** (gap D1): every recipe it runs reads files or talks to
 *   an operator-approved URL. Deeper audit that executes the app's own build/tests requires an
 *   isolation model that does not exist yet; it is refused rather than silently run.
 * - **`--url` is guarded** (gap D6): private, loopback, and link-local targets are refused unless
 *   `--allow-local` opts into local development explicitly.
 */

export interface AuditOptions {
  readonly target: string;
  readonly out?: string;
  readonly depth: Depth;
  readonly url?: ApprovedUrl;
  readonly policyRoot: string;
  readonly now: Date;
}

export interface AuditOutcome extends CommandOutcome {
  readonly reportPaths?: {
    readonly markdown: string;
    readonly html: string;
    readonly json: string;
    readonly sarif: string;
  };
}

/** Recipes that only run at standard depth and above. Quick mode is a fast static pass. */
const NOT_AT_QUICK: ReadonlySet<string> = new Set(['gitleaks/history', 'build/client-assets', 'web/http-requirements']);

function slugify(name: string): string {
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 100);
  return slug.length > 0 ? slug : 'audit-target';
}

function isInside(parent: string, child: string): boolean {
  // R1-02: segment-aware containment — `..foo` is a legitimate name, `..` and `../x` are escapes,
  // and an absolute remainder is not a containment answer.
  const rel = relative(resolve(parent), resolve(child));
  return rel === '' || (rel !== '..' && !rel.startsWith(`..${sep}`) && !isAbsolute(rel));
}

function manifestFor(detection: Detection, options: AuditOptions, policyCommit: string, catalogueDigest: string, urlEnvironment: 'local' | 'production'): ManifestRecord & { name: string } {
  const features: Record<string, unknown> = {};
  for (const [feature, record] of Object.entries(detection.features)) {
    if (record.state === 'enabled') {
      features[feature] = {
        state: 'enabled',
        notes: `detected: ${record.evidence.map((item) => `${item.file} (${item.detail})`).join('; ') || 'detected'}`,
        evidence_refs: record.evidence.slice(0, 16).map((item) => item.file),
      };
    } else {
      features[feature] = { state: 'unknown', notes: 'not detected by the static scan; audit mode cannot prove absence, so this stays unknown' };
    }
  }

  // The full manifest document (schema `app/v1`) is built as data; the narrow ManifestRecord type
  // is the machinery's view of it.
  const document: Record<string, unknown> = {
    schema_version: 'app/v1',
    id: slugify(basename(options.target)),
    name: basename(options.target),
    description: 'Ephemeral manifest generated by audit mode from static detection. It is written to the audit output directory, never to the audited project.',
    stack: {
      kind: detection.stack.kind === 'nextjs' && detection.profiles.some((profile) => profile.id === 'supabase') ? 'nextjs-supabase' : 'other',
      runtime_versions: {},
    },
    features,
    data: { classification: 'unknown' },
    exposed_interfaces: [],
    environments: [
      { name: 'local', kind: 'local', internet_facing: false, separated: true },
      ...(urlEnvironment === 'production' ? [{ name: 'production', kind: 'production', internet_facing: true }] : []),
    ],
    profiles: detection.profiles.map((profile) => profile.id),
    policy_lock: {
      repository: 'audited-by-sechard',
      commit: policyCommit,
      policy_digest: sha256Hex(`${policyCommit}:${catalogueDigest}`),
    },
    maintainer: { name: 'unknown (audit mode)' },
    updated_at: options.now.toISOString(),
  };
  return document as unknown as ManifestRecord & { name: string };
}

export async function auditCommand(options: AuditOptions): Promise<AuditOutcome> {
  const target = resolve(options.target);
  const out = resolve(options.out ?? join(process.cwd(), `sechard-audit-${options.now.toISOString().replace(/[:.]/g, '-')}-${randomUUID().slice(0, 8)}`));

  // A-02 / PR-03: output confinement is resolved against real paths — an output symlink (or a
  // symlinked ancestor) pointing into the audited tree must be rejected before anything is
  // created. The deepest existing ancestor is resolved, because the output directory itself
  // typically does not exist yet. A concurrent link swap between this check and later writes is
  // explicitly out of scope and documented here: the audit never writes inside the target, and
  // every written artifact goes through writeAtomic under the checked prefix.
  const targetReal = realpathSync(target);
  // Walk up with lstat (never following links) to the deepest existing ancestor, then resolve it.
  // A symlink that resolves nowhere (dangling) cannot be proven confined: refuse.
  let probe = out;
  for (;;) {
    try {
      lstatSync(probe);
      break;
    } catch {
      const parent = dirname(probe);
      if (parent === probe) break;
      probe = parent;
    }
  }
  let outBaseReal: string;
  try {
    outBaseReal = join(realpathSync(probe), relative(probe, out));
  } catch {
    return {
      exitCode: 2,
      stdout: [],
      stderr: [
        'audit: the output path could not be resolved to a real location (dangling symlink?), refusing',
        `  out ${out}`,
      ],
    };
  }
  // R1-02: the guard must cover descendants, not just the root — a pre-existing out/records
  // symlink into the target would otherwise carry every record write inside the audited tree.
  const outputSymlinks: string[] = [];
  const scanOutput = (dir: string, depth: number): void => {
    if (depth > 6 || outputSymlinks.length > 20) return;
    let entries: string[];
    try {
      entries = readdirSync(dir);
    } catch (error) {
      // ENOENT is the fresh-tree case (nothing pre-exists to alias); anything else — an
      // unreadable-but-writable directory that could hide a symlink — refuses fail-closed.
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
        throw new Error(`the output directory ${dir} cannot be inspected (${(error as Error).message}); refusing to write through an unverifiable path`);
      }
      return;
    }
    for (const entry of entries) {
      const full = join(dir, entry);
      let stats;
      try {
        stats = lstatSync(full);
      } catch {
        continue;
      }
      if (stats.isSymbolicLink()) outputSymlinks.push(relative(out, full));
      // R1-02: the recursion is deliberately outside the entry try — a refusal from a deeper
      // level (an unreadable directory that could hide a symlink) must propagate, not be
      // swallowed as if this entry were merely missing.
      else if (stats.isDirectory()) scanOutput(full, depth + 1);
    }
  };
  // R1-02: an output tree we cannot inspect cannot be proven safe — refuse rather than continue
  // (an unreadable-but-writable out/ can hide a records symlink into the target).
  scanOutput(out, 0);
  if (outputSymlinks.length > 0) {
    return {
      exitCode: 2,
      stdout: [],
      stderr: [
        'audit: the output directory contains symlinks; refusing to write through them',
        ...outputSymlinks.slice(0, 5).map((entry) => `  out/${entry}`),
        '  Remove the symlinks or choose a fresh --out directory.',
      ],
    };
  }
  if (isInside(targetReal, outBaseReal)) {
    return {
      exitCode: 2,
      stdout: [],
      stderr: [
        'audit: the output directory must live outside the audited project',
        `  target ${target} (real: ${targetReal})`,
        `  out    ${out} (resolves to ${outBaseReal})`,
        '  Audit mode never writes to the audited project; pass --out pointing outside it.',
      ],
    };
  }

  const recordsRoot = join(out, 'records');
  mkdirSync(join(recordsRoot, '.hardening'), { recursive: true });

  const paths: Paths = { appRoot: target, policyRoot: options.policyRoot, recordsRoot };

  // 1. Policy must load: the ephemeral manifest pins the real policy commit, so it is generated
  //    only after the policy identity is known.
  const policyOutcome = loadPolicy(paths);
  if (policyOutcome.value === undefined || policyOutcome.issues.length > 0) {
    return {
      exitCode: 2,
      stdout: [],
      stderr: ['audit: policy inputs are invalid', ...policyOutcome.issues.map((issue) => `  ${issue.code}${issue.file === undefined ? '' : ` ${issue.file}`}: ${issue.message}`)],
    };
  }
  const policy = policyOutcome.value;

  // 2. Detection is read-only and recorded; it is the input to the manifest, never a guess.
  let detection: Detection;
  try {
    detection = detectStackAndFeatures(target);
  } catch (error) {
    return { exitCode: 2, stdout: [], stderr: [`audit: ${basename(target)} cannot be audited: ${(error as Error).message}`] };
  }

  // A composed profile that is not loadable policy is dropped and recorded, never silently kept.
  const loadableProfileIds = new Set(policy.profiles.map((profile) => profile.id));
  const dropped = detection.profiles.filter((profile) => !loadableProfileIds.has(profile.id));
  const composedProfiles = detection.profiles.filter((profile) => loadableProfileIds.has(profile.id));
  if (dropped.length > 0) {
    detection = {
      ...detection,
      profiles: composedProfiles,
      gaps: [...detection.gaps, `profile(s) ${dropped.map((profile) => profile.id).join(', ')} were composed by detection but are not loadable policy; they were dropped`],
    };
  }

  const urlEnvironment = options.url?.environment ?? 'local';

  // 3. The ephemeral manifest. It must validate like any consumer manifest, or the generator is
  //    the bug; that is checked before anything runs.
  const manifest = manifestFor(detection, options, policy.policyCommit, policy.controlCatalogueDigest, urlEnvironment);
  const manifestFile = join(recordsRoot, '.hardening', 'app.yaml');
  const manifestText = stringifyYaml(manifest);
  const manifestCheck = validateAgainstSchema('app', JSON.parse(JSON.stringify(manifest)) as unknown as Record<string, unknown>, 'audit-manifest');
  if (!manifestCheck.valid) {
    return {
      exitCode: 2,
      stdout: [],
      stderr: [
        'audit: the generated manifest does not validate; this is a defect in the audit generator',
        ...manifestCheck.issues.map((issue) => `  ${issue.path ?? '$'}: ${issue.message}`),
      ],
    };
  }
  // R1-04: generated records carry detection evidence (file names, details) — scrub before persisting.
  writeAtomic(manifestFile, redactSecrets(manifestText));

  // 4. Live target inventory, generated from the approved URL. The inventory is validated by the
  //    same loader the recipe uses, so an invalid generated inventory can never be honoured.
  if (options.url !== undefined) {
    const inventory = {
      schema_version: 'live-targets/v1',
      targets: [
        {
          id: 'audit-live-target',
          scheme: options.url.scheme,
          host: options.url.host,
          ...(options.url.port === undefined ? {} : { port: options.url.port }),
          environment: options.url.environment,
          routes: ['/'],
          approved_redirect_hosts: [options.url.host],
          ...(options.url.scheme === 'https' ? { tls: { required: true } } : {}),
          response_limits: { max_bytes: 1024 * 1024, timeout_ms: 10_000 },
          requirements: [{ route_prefix: '/' }],
        },
      ],
    };
    writeAtomic(join(recordsRoot, '.hardening', 'targets.yaml'), redactSecrets(stringifyYaml(inventory)));
    const loaded = loadTargetInventory(join(recordsRoot, '.hardening', 'targets.yaml'));
    if (loaded.inventory === undefined || loaded.issues.length > 0) {
      return {
        exitCode: 2,
        stdout: [],
        stderr: ['audit: the generated target inventory is not usable', ...loaded.issues.map((issue) => `  ${issue}`)],
      };
    }
  }

  // 5. Plan through the real machinery.
  const runId = `audit-${options.now.toISOString().replace(/[:.]/g, '-')}-${randomUUID().slice(0, 8)}`;
  const planned = planCommand(paths, { stage: 'pr', environment: urlEnvironment, runId, now: options.now }) as PlanOutcome;
  if (planned.plan === undefined) {
    return { exitCode: planned.exitCode, stdout: planned.stdout, stderr: ['audit: planning failed', ...planned.stderr] };
  }
  const planPath = join(out, 'plan.json');
  writeJson(planPath, JSON.parse(redactSecrets(JSON.stringify(planned.plan))) as typeof planned.plan);

  // 6. Check through the real machinery. Quick depth excludes the slow and live recipes; the
  //    excluded checks report unsupported with the reason rather than vanishing.
  // R1-05: raw scanner output never enters the published output tree. It is written to private
  // staging (0700, outside `out`) and removed on every path — including a failed report write.
  const rawStaging = mkdtempSync(join(tmpdir(), 'sechard-raw-'));
  chmodSync(rawStaging, 0o700);
  let checked: Awaited<ReturnType<typeof checkCommand>>;
  try {
    checked = await checkCommand(paths, {
    planPath,
    runId,
    outDir: out,
    rawDir: rawStaging,
    now: options.now,
    ...(
      options.depth === 'quick'
        ? { skipRecipes: [...NOT_AT_QUICK], skipReason: 'not run at --depth quick; rerun at standard depth for the full set' }
        : {}
    ),
  });
  } finally {
    rmSync(rawStaging, { recursive: true, force: true });
  }
  if (checked.results !== undefined) {
    writeJson(join(out, 'results.json'), JSON.parse(redactSecrets(JSON.stringify(checked.results))) as typeof checked.results);
  }

  // 7. Gate through the real machinery. An audit is advisory: the decision is reported, and a
  //    blocked gate means obligations exist that source alone cannot satisfy.
  const gated = gateCommand(paths, { planPath, resultsPath: join(out, 'results.json'), now: options.now });
  if (gated.decision === undefined) {
    return { exitCode: 2, stdout: gated.stdout, stderr: ['audit: evaluation failed', ...gated.stderr] };
  }

  const built = buildReport({
    decision: gated.decision,
    plan: planned.plan,
    results: checked.results ?? [],
    manualEvidence: [],
    exceptions: [],
    appId: manifest.id,
    appName: manifest.name,
    sourceCommit: planned.plan.inputs.source_commit,
    sourceClean: planned.plan.inputs.source_dirty !== true,
    policyRepository: 'audited-by-sechard',
    policyCommit: policy.policyCommit,
    controlCatalogueDigest: policy.controlCatalogueDigest,
    gatePolicyDigest: policy.gatePolicyDigest,
    generatedAt: options.now,
    runId,
  });

  const report = buildAuditReport({
    target,
    targetName: basename(target),
    detection,
    plan: planned.plan,
    results: checked.results ?? [],
    decision: gated.decision,
    evidence: built.evidence,
    controls: policy.controls,
    depth: options.depth,
    ...(options.url === undefined ? {} : { url: options.url }),
    generatedAt: options.now,
    policyCommit: policy.policyCommit,
  });

  const reportPaths = {
    markdown: join(out, 'report.md'),
    html: join(out, 'report.html'),
    json: join(out, 'report.json'),
    sarif: join(out, 'report.sarif'),
  };
  // A-03 (PR-04): the persistence boundary. Findings are redacted at intake, but the report is
  // the last line of defence before bytes hit disk: every artifact is scrubbed with the provider
  // patterns (including values not assigned to a variable named "secret"), and raw scanner
  // output is not retained in ordinary mode at all. writeAtomic already uses 0600; that is an
  // additional protection, never the control.
  const scrubbed = {
    markdown: redactSecrets(report.markdown),
    html: redactSecrets(report.html),
    json: redactSecrets(report.json),
    sarif: redactSecrets(report.sarif),
  };
  writeAtomic(reportPaths.markdown, scrubbed.markdown);
  writeAtomic(reportPaths.html, scrubbed.html);
  writeAtomic(reportPaths.json, scrubbed.json);
  writeAtomic(reportPaths.sarif, scrubbed.sarif);
  writeAtomic(join(out, 'evidence.json'), redactSecrets(JSON.stringify(built.evidence, null, 2) + '\n'));


  const errored = (checked.results ?? []).filter((result: CheckResult) => result.outcome === 'error');
  const bySeverity = new Map<string, number>();
  for (const finding of report.findings) {
    bySeverity.set(finding.severity, (bySeverity.get(finding.severity) ?? 0) + 1);
  }

  const stdout = [
    `audit: ${basename(target)} — stack ${detection.stack.kind}, profiles ${composedProfiles.map((profile) => profile.id).join(' + ') || 'none'}`,
    `  checks: ${checked.results?.length ?? 0} result(s), ${errored.length} error(s)`,
    `  findings: ${report.findings.length}${report.findings.length === 0 ? '' : ` (${[...bySeverity.entries()].map(([severity, count]) => `${count} ${severity}`).join(', ')})`}`,
    `  security score: ${report.securityScore.score === null ? 'no findings recorded' : String(report.securityScore.score)} — ${report.securityScore.verdict}`,
    `  quality score: ${report.qualityScore.score === null ? 'not assessed' : String(report.qualityScore.score)} — ${report.qualityScore.verdict}`,
    `  could not check: ${report.couldNotCheck.length} item(s) — listed in the report`,
    `  reports: ${reportPaths.markdown}`,
    `           ${reportPaths.html}`,
    `           ${reportPaths.json} (machine-readable), ${reportPaths.sarif} (GitHub code scanning)`,
    '  the audited project was not modified',
  ];

  return {
    exitCode: errored.length > 0 ? 1 : 0,
    stdout,
    stderr: [],
    reportPaths,
  };
}
