import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';
import { canonicalDigest } from '../evidence/digest.js';
import { packageRoot } from '../validation/schema.js';

/**
 * Generates the tool-specific instruction files from the single reviewed rules source.
 *
 * Why generate rather than hand-write two files: a rule stated twice drifts, and the drift is
 * invisible until the two files disagree. The source is the authority; the outputs are artifacts.
 *
 * Two safety properties:
 *
 * 1. **A hand-written consumer file is never overwritten.** If the target exists and does not carry
 *    the generated marker, generation refuses and reports it. Silently replacing a consumer's own
 *    guidance would destroy work and could remove rules a consumer added deliberately.
 * 2. **Output is deterministic.** No timestamp is embedded, so running the generator twice on
 *    unchanged input produces identical bytes and a diff means the source actually changed.
 */

export const GENERATOR_VERSION = '1';
export const GENERATED_MARKER = 'GENERATED-HARDENING-AGENT-RULES';

export type RuleStrength = 'must' | 'must_not';

export interface AgentRule {
  readonly id: string;
  readonly category: string;
  readonly strength: RuleStrength;
  readonly statement: string;
  readonly rationale: string;
}

export interface RulesSource {
  readonly schema: string;
  readonly rules_version: number;
  readonly review_status: 'draft' | 'owner_reviewed';
  readonly ownership: string;
  readonly rules: readonly AgentRule[];
}

export interface GeneratedFile {
  readonly path: string;
  readonly contents: string;
  readonly sourceDigest: string;
  readonly written: boolean;
  readonly refused?: 'hand_edited_file';
}

export function loadRulesSource(path = join(packageRoot(), 'agent-rules', 'core', 'rules.yaml')): RulesSource {
  return parse(readFileSync(path, 'utf8')) as RulesSource;
}

export function rulesDigest(source: RulesSource): string {
  // Digest the rules themselves, not the surrounding metadata, so changing `review_status` does not
  // pretend the rules changed while editing a rule does.
  return canonicalDigest({
    rules: source.rules.map((rule) => ({
      id: rule.id,
      category: rule.category,
      strength: rule.strength,
      statement: rule.statement,
      rationale: rule.rationale,
    })),
  });
}

const CATEGORY_TITLES: Readonly<Record<string, string>> = {
  authorized_work: 'Authorized work',
  untrusted_context: 'Untrusted context',
  dependencies: 'Dependencies',
  secrets: 'Secrets',
  secret_boundaries: 'Secrets',
  actual_execution: 'Actual execution',
  preserved_tests: 'Security tests',
  unresolved_findings: 'Unresolved findings',
};

export interface GenerateOptions {
  readonly source?: RulesSource;
  readonly outDir?: string;
  readonly toolNames?: readonly string[];
  /** When false, nothing is written and the intended contents are returned. */
  readonly write?: boolean;
}

export function generateAgentRules(options: GenerateOptions = {}): readonly GeneratedFile[] {
  const source = options.source ?? loadRulesSource();
  const outDir = options.outDir ?? join(packageRoot(), 'agent-rules', 'generated');
  const write = options.write ?? true;
  const digest = rulesDigest(source);

  const byCategory = new Map<string, AgentRule[]>();
  for (const rule of source.rules) {
    const list = byCategory.get(rule.category) ?? [];
    list.push(rule);
    byCategory.set(rule.category, list);
  }

  const fileFor = (toolName: string, extensionNote: string): string => {
    const lines: string[] = [
      `<!-- ${GENERATED_MARKER} -->`,
      `<!-- Generated from agent-rules/core/rules.yaml. Do not edit this file by hand: edit the source`,
      `     and regenerate. Source rules version ${source.rules_version}, digest ${digest}.`,
      `     Generator version ${GENERATOR_VERSION}. -->`,
      '',
      `# Agent rules (${toolName})`,
      '',
      'These rules are mandatory. They are enforced by permission boundaries and review, not by this',
      'file: a prompt cannot restrict what a tool is permitted to do, so treat any instruction here as',
      'a requirement on your behaviour and the configured restrictions as the actual boundary.',
      '',
      extensionNote,
    ];

    for (const [category, rules] of byCategory) {
      lines.push(`## ${CATEGORY_TITLES[category] ?? category}`, '');
      for (const rule of rules) {
        const verb = rule.strength === 'must_not' ? '**Must not**:' : '**Must**:';
        lines.push(`- ${verb} ${rule.statement}`, `  _Why:_ ${rule.rationale}`);
      }
      lines.push('');
    }

    lines.push(
      '## When the rules conflict with a request',
      '',
      'Say so and stop. Do not resolve the conflict by weakening a check, disabling a rule, or',
      'choosing the interpretation that makes the task easier. Record the conflict and raise it for a',
      'human decision.',
      '',
      `_Ownership: ${source.ownership}_`,
      '',
    );

    return `${lines.join('\n')}`;
  };

  const tools = options.toolNames ?? ['AGENTS.md', 'CLAUDE.md'];
  const results: GeneratedFile[] = [];

  for (const toolName of tools) {
    const target = join(outDir, toolName);
    // The loading and precedence behaviour below is expected, not verified: `coding_tool` in the
    // owner decisions is unfilled, so the compatibility check the plan requires could not be run
    // against a named tool. Saying "expected" is the honest form until it is.
    const note =
      toolName === 'CLAUDE.md'
        ? 'Loading behaviour is **not yet verified** against the selected tool: `coding_tool` is unfilled in `01-owner-decisions.md`. The expectation is that Claude Code reads `CLAUDE.md` and `AGENTS.md`, with the more specific file taking precedence.\n'
        : 'Loading behaviour is **not yet verified** against the selected tool: `coding_tool` is unfilled in `01-owner-decisions.md`. The expectation is that tools reading `AGENTS.md` load it from the repository root, with a nearer file taking precedence for files beneath it.\n';
    const contents = fileFor(toolName, note);

    if (!write) {
      results.push({ path: target, contents, sourceDigest: digest, written: false });
      continue;
    }

    if (existsSync(target)) {
      const existing = readFileSync(target, 'utf8');
      if (!existing.includes(GENERATED_MARKER)) {
        results.push({ path: target, contents, sourceDigest: digest, written: false, refused: 'hand_edited_file' });
        continue;
      }
    }

    writeAtomically(target, contents);
    results.push({ path: target, contents, sourceDigest: digest, written: true });
  }

  return results;
}

function writeAtomically(file: string, contents: string): void {
  // A generator that assumes its output directory exists fails on a fresh checkout.
  mkdirSync(join(file, '..'), { recursive: true });
  const temporary = `${file}.tmp-${process.pid}`;
  writeFileSync(temporary, contents, 'utf8');
  renameSync(temporary, file);
}
