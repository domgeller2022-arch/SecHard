#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { coverageSummary, loadStandardMapping, renderCoverageMatrix } from '../dist/domain/standards-coverage.js';

const root = fileURLToPath(new URL('..', import.meta.url));

// The standards mapped at requirement level (Batch S1). ASVS additionally renders its level-1
// summary, because the owner reviews ASVS L1 line by line.
const STANDARDS = ['asvs', 'owasp-top-10', 'owasp-api-top-10', 'nist-ssdf', 'osps', 'mvsp', 'asd-sbd', 'mcp-top-10'];

const outDir = join(root, 'controls', 'coverage');
mkdirSync(outDir, { recursive: true });

let failed = false;
const index: string[] = [
  '# Standards coverage matrices',
  '',
  'Generated by `tools/generate-coverage.ts` from `controls/mappings/*.yaml`. Do not edit by hand.',
  'Every mapped requirement carries a method or a recorded gap; all relationships are related_risk.',
  '',
  '| Standard | Edition | Requirements | Automated | Manual | Gap | Not applicable |',
  '| --- | --- | --- | --- | --- | --- | --- |',
];

for (const standard of STANDARDS) {
  const loaded = loadStandardMapping(standard);
  if (loaded.mapping === undefined) {
    console.error(`coverage: ${standard}: ${loaded.issues.join('; ')}`);
    failed = true;
    continue;
  }
  const matrixPath = join(outDir, `${standard}.md`);
  writeFileSync(matrixPath, renderCoverageMatrix(loaded.mapping));

  const total = coverageSummary(loaded.mapping);
  const l1 = standard === 'asvs' ? coverageSummary(loaded.mapping, [1]) : undefined;
  index.push(
    `| ${standard} | ${loaded.mapping.edition} | ${total.total} | ${total.byMethod['automated'] ?? 0} | ${total.byMethod['manual'] ?? 0} | ${total.byMethod['gap'] ?? 0} | ${total.byMethod['not_applicable'] ?? 0} |`,
  );
  if (l1 !== undefined) {
    index.push(
      `| - ${standard} L1 | - | ${l1.total} | ${l1.byMethod['automated'] ?? 0} | ${l1.byMethod['manual'] ?? 0} | ${l1.byMethod['gap'] ?? 0} | ${l1.byMethod['not_applicable'] ?? 0} |`,
    );
  }
  console.log(`coverage: ${standard} (${String(total.total)} requirements) -> ${matrixPath}`);
}

index.push('', '## The per-audit statement', '',
  'The audit report states the per-application version of these numbers - which requirements the',
  'composed profiles and wired recipes could actually check for the audited application. The',
  'matrices above are the kit-level truth; the report is the application-level truth, and the two',
  'are labelled differently on purpose.', '');
writeFileSync(join(outDir, 'README.md'), index.join('\n') + '\n');
if (failed) process.exit(1);
