#!/usr/bin/env node
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateAgentRules } from '../dist/agent/generate.js';

const root = fileURLToPath(new URL('..', import.meta.url));

const results = generateAgentRules({ outDir: join(root, 'agent-rules', 'generated') });

let refused = 0;
for (const result of results) {
  if (result.refused === 'hand_edited_file') {
    refused += 1;
    process.stderr.write(
      `refused to overwrite ${result.path}: it was not generated by this tool. Merge the rules by hand, or remove the file deliberately.\n`,
    );
    continue;
  }
  process.stdout.write(`generated ${result.path} (source digest ${result.sourceDigest.slice(0, 12)}…)\n`);
}

process.exit(refused === 0 ? 0 : 1);
